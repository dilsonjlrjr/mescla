export type Lang = keyof typeof dict;
export type DictKey = keyof typeof dict.pt;

export const LANGS: { code: Lang; label: string }[] = (Object.keys(dict) as Lang[]).map((code) => ({
  code,
  label: dict[code]._name
}));

const STORAGE_KEY = 'mescla-lang';

function loadLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && saved in dict) return saved as Lang;
  } catch {
    // localStorage indisponível (SSR, storage bloqueado) — segue com o padrão
  }
  return 'pt';
}

export const i18n = $state<{ lang: Lang }>({ lang: loadLang() });

export function setLang(lang: Lang) {
  i18n.lang = lang;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    // persistência é conveniência; falha não bloqueia a troca de idioma (RG-23/NFR-09)
  }
}

export function t(key: DictKey, params?: Record<string, string | number>): string {
  const entry = dict[i18n.lang] as Record<string, string>;
  let text = entry[key] ?? (dict.pt as Record<string, string>)[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

// RG-23: separador decimal segue o idioma (ΔE 1,4 em pt/es/fr; 1.4 em en)
export function decimal(n: number, digits = 1): string {
  const fixed = n.toFixed(digits);
  return dict[i18n.lang]._dec === ',' ? fixed.replace('.', ',') : fixed;
}
